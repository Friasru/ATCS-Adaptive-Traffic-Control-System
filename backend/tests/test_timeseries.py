import pytest

from app import db
from app.models import Run
from app.services.timeseries import MAX_POINTS, halting_series

# Same layout as SUMO 1.18 --summary-output (header comment, then <step> rows).
HEADER = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- generated by Eclipse SUMO -->\n<summary>\n'
STEP = (
    '    <step time="{t:.2f}" loaded="4" inserted="4" running="4" waiting="0" ended="0" '
    'arrived="0" collisions="0" teleports="0" halting="{h}" stopped="0" meanWaitingTime="0.00" '
    'meanTravelTime="-1.00" meanSpeed="0.00" meanSpeedRelative="0.00" duration="0"/>\n'
)


def write_summary(sim_dir, run_id, steps):
    out = sim_dir / "output"
    out.mkdir(exist_ok=True)
    body = "".join(STEP.format(t=t, h=h) for t, h in steps)
    (out / f"summary_run_{run_id}.xml").write_text(HEADER + body + "</summary>\n")


@pytest.fixture
def sim_dir(app, tmp_path):
    app.config["SIMULATION_DIR"] = str(tmp_path)
    return tmp_path


def add_run(app, status="completed"):
    with app.app_context():
        run = Run(scenario_id=1, controller="wait_time", status=status)
        db.session.add(run)
        db.session.commit()
        return run.id


def test_returns_halting_counts(client, app, sim_dir):
    run_id = add_run(app)
    write_summary(sim_dir, run_id, [(0, 4), (1, 3), (2, 0)])
    response = client.get(f"/api/runs/{run_id}/timeseries")
    assert response.status_code == 200
    assert response.get_json() == {
        "run_id": run_id,
        "controller": "wait_time",
        "time_s": [0.0, 1.0, 2.0],
        "halting": [4, 3, 0],
    }


def test_downsampled_to_window_means(client, app, sim_dir):
    run_id = add_run(app)
    write_summary(sim_dir, run_id, [(t, t % 7) for t in range(3644)])
    data = client.get(f"/api/runs/{run_id}/timeseries").get_json()
    assert len(data["time_s"]) == len(data["halting"])
    assert MAX_POINTS - 10 <= len(data["time_s"]) <= MAX_POINTS
    # windows of 19 steps starting at 0, 19, 38, ...
    assert data["time_s"][:3] == [0.0, 19.0, 38.0]
    assert data["time_s"][-1] == 3629.0
    assert data["halting"][0] == round(sum(t % 7 for t in range(19)) / 19, 2)
    assert data["halting"][-1] == round(sum(t % 7 for t in range(3629, 3644)) / 15, 2)


def test_window_mean_does_not_alias(tmp_path):
    # a 2-step on/off signal: every-n-th sampling would read all 10s or all 0s
    write_summary(tmp_path, 1, [(t, 10 * (t % 2)) for t in range(1000)])
    series = halting_series(tmp_path / "output" / "summary_run_1.xml", max_points=100)
    assert {h for _, h in series} == {5.0}


def test_halting_series_short_file_untouched(tmp_path):
    write_summary(tmp_path, 1, [(0, 1), (1, 2)])
    assert halting_series(tmp_path / "output" / "summary_run_1.xml") == [(0.0, 1), (1.0, 2)]


def test_missing_file_is_404(client, app, sim_dir):
    run_id = add_run(app)
    response = client.get(f"/api/runs/{run_id}/timeseries")
    assert response.status_code == 404
    assert response.get_json() == {"error": "timeseries not available"}


def test_unknown_run_is_404(client, sim_dir):
    assert client.get("/api/runs/999/timeseries").get_json() == {"error": "run not found"}


@pytest.mark.parametrize("status", ["pending", "running", "failed"])
def test_unfinished_run_is_404_even_with_stale_file(client, app, sim_dir, status):
    run_id = add_run(app, status=status)
    write_summary(sim_dir, run_id, [(0, 1)])
    assert client.get(f"/api/runs/{run_id}/timeseries").status_code == 404


def test_corrupt_file_is_sanitized_500(client, app, sim_dir):
    run_id = add_run(app)
    (sim_dir / "output").mkdir()
    (sim_dir / "output" / f"summary_run_{run_id}.xml").write_text("<summary><step time=")
    response = client.get(f"/api/runs/{run_id}/timeseries")
    assert response.status_code == 500
    text = response.get_data(as_text=True)
    assert str(sim_dir) not in text
    assert "summary_run" not in text


