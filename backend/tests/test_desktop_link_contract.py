"""Documents produced by the desktop link (Phase 5b) pass the backend's validators.

monitor/tests/data/desktop_link_documents.json is generated by the desktop's
own builders (monitor/tests/test_desktop_link_contract.py keeps it current).
The backend tests read only that JSON file, never the monitor's code.
"""

import json
from pathlib import Path

import pytest

from app.services import desktop_schema

FIXTURE = Path(__file__).resolve().parents[2] / "monitor" / "tests" / "data" / "desktop_link_documents.json"


@pytest.fixture(scope="module")
def docs():
    if not FIXTURE.is_file():
        pytest.skip("monitor contract fixture not present")
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


@pytest.mark.parametrize("name", ["desktop_status_idle", "desktop_status_recording"])
def test_desktop_status(docs, name):
    out, _ = desktop_schema.validate_status(docs[name])
    assert out == docs[name]


def test_crossing_events(docs):
    out, _, _ = desktop_schema.validate_events(docs["crossing_events"])
    assert out == docs["crossing_events"]


@pytest.mark.parametrize("name", ["session_summary_completed", "session_summary_interrupted"])
def test_session_summary(docs, name):
    out, _, _ = desktop_schema.validate_summary(docs[name])
    assert out == docs[name]


def test_interrupted_summary_is_marked_incomplete(docs):
    s = docs["session_summary_interrupted"]
    assert s["status"] == "interrupted" and s["stats_complete"] is False
    assert s["crossing_event_count"] == sum(s["crossings"].values())
